pub fn git_tf(language: Language, message: GitMsg, args: &[&str]) -> String {
    let mut result = git_t(language, message).to_string();
    for (index, value) in args.iter().enumerate() {
        result = result.replace(&format!("{{{index}}}"), value);
    }
    result
}

